import { resolve } from 'node:path';
import * as Rx from 'rxjs';
import { openStore } from '../../server/src/db/store';
import { createVault } from '../../server/src/lib/vault';
import { getNetworkConfig } from '../../server/src/config/networks';
import { deriveKeys } from '../../server/src/chain/keys';
import { openWallet } from '../../server/src/chain/wallet-runtime';
const store = openStore(resolve('data/minter.db'));
const vault = createVault(process.env.MASTER_PW!, Buffer.from(store.getMeta('vault_salt')!, 'hex'));
const w = store.getWallet(process.env.WALLET_ID!)!;
const snap = JSON.parse(vault.decrypt(store.getWalletState(w.id)!.blob));
const network = getNetworkConfig('preview', { proofServerUrl: 'http://localhost:6301' } as any);
const keys = await deriveKeys(vault.decrypt(w.encryptedMnemonic), network.networkId);
const ow = await openWallet(network, keys, snap);
const s = await ow.facade.waitForSyncedState();
const bal = s.unshielded.balances;
for (const [color, v] of Object.entries(bal)) console.log(color.slice(0, 12), String(v));
console.log('PAPA1 color present:', String(bal['0693f95a57376da28654dfcf008826c15bbfb3a7efccb54c6a7c0b0851363650'] ?? 0));
await ow.facade.stop(); process.exit(0);
